def main():
    if not os.path.exists(FEDB):
        urllib.request.urlretrieve(RAW + 'dist/exercises.json', FEDB)
    db = {e['id']: e for e in json.load(open(FEDB, encoding='utf-8'))}
    out = []
    for xid, (name, fid, muscles, equip, mistakes, steps) in X.items():
        e = db.get(fid) if fid else None
        if fid and not e:
            sys.exit(f'{xid}: free-exercise-db id {fid} not found')
        imgs = []
        svg_dir = os.path.join(ROOT, 'media', xid)
        if not e and os.path.exists(os.path.join(svg_dir, '0.svg')):
            imgs = [f'media/{xid}/{i}.svg' for i in (0, 1) if os.path.exists(os.path.join(svg_dir, f'{i}.svg'))]
        if e:
            d = os.path.join(ROOT, 'media', xid)
            os.makedirs(d, exist_ok=True)
            for i, rel in enumerate(e['images'][:2]):
                dst = os.path.join(d, f'{i}.jpg')
                if not os.path.exists(dst):
                    urllib.request.urlretrieve(RAW + 'exercises/' + rel, dst)
                imgs.append(f'media/{xid}/{i}.jpg')
        out.append({'id': xid, 'name': name, 'muscles': muscles, 'equipment': equip,
                    'img': imgs, 'steps': steps or (e['instructions'] if e else []),
                    'mistakes': mistakes, 'source': fid})
    os.makedirs(os.path.join(ROOT, 'exercises'), exist_ok=True)
    with open(os.path.join(ROOT, 'exercises', 'catalog.json'), 'w', encoding='utf-8') as f:
        json.dump({'exercises': out}, f, ensure_ascii=False, indent=1)
    print(len(out), 'exercises,', sum(1 for o in out if o['img']), 'with photos')

if __name__ == '__main__':
    main()

